from abc import ABC, abstractmethod
from typing import Any, AsyncGenerator, Dict, List, Optional
from pydantic import BaseModel, Field


class LLMMessage(BaseModel):
    """Normalized chat message structure."""
    role: str = Field(description="Role: 'system', 'user', 'assistant', 'tool'")
    content: str = Field(description="Textual content of the message")
    name: Optional[str] = Field(default=None, description="Optional name for tool / user identification")
    tool_calls: Optional[List[Dict[str, Any]]] = Field(default=None, description="Tool calls generated by assistant")

    def to_dict(self) -> Dict[str, Any]:
        d = {"role": self.role, "content": self.content}
        if self.name:
            d["name"] = self.name
        if self.tool_calls:
            d["tool_calls"] = self.tool_calls
        return d


class LLMChunk(BaseModel):
    """Single streamed token or delta event."""
    delta: str = ""
    finish_reason: Optional[str] = None
    tool_call_delta: Optional[Dict[str, Any]] = None
    provider: str = ""
    model: str = ""


class LLMResponse(BaseModel):
    """Complete aggregated LLM response."""
    content: str
    tool_calls: Optional[List[Dict[str, Any]]] = None
    provider: str
    model: str
    tokens_used: int = 0


class LLMProvider(ABC):
    """Abstract base class for all AI inference providers."""

    name: str

    @abstractmethod
    async def is_available(self) -> bool:
        """Probes the provider endpoint to test health and availability."""
        pass

    @abstractmethod
    async def list_models(self) -> List[str]:
        """Lists available models for this provider."""
        pass

    @abstractmethod
    async def generate_stream(
        self,
        messages: List[LLMMessage],
        model: Optional[str] = None,
        tools: Optional[List[Dict[str, Any]]] = None,
        temperature: float = 0.7,
    ) -> AsyncGenerator[LLMChunk, None]:
        """Streams generation chunks asynchronously."""
        yield LLMChunk()

    @abstractmethod
    async def generate(
        self,
        messages: List[LLMMessage],
        model: Optional[str] = None,
        tools: Optional[List[Dict[str, Any]]] = None,
        temperature: float = 0.7,
    ) -> LLMResponse:
        """Aggregates a complete generation response."""
        pass

